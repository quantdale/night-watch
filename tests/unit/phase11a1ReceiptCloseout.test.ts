// 13. Privacy sentinel sweep — no raw-value / sentinel leakage in receipts.
// ===========================================================================

test.describe('Phase 11A.1 §13: privacy sentinel sweep', () => {
  test('receipt built from partial-coverage evaluation has no sentinel leaks', () => {
    const body = generateExchangeArray(130);
    const expectation = collectionExpectation();
    const result = evaluateCollection(body, expectation);
    expect(result.outcome).toBe('PARTIAL_COVERAGE');

    // Build receipt using the same parameters the hook would derive.
    const receipt = buildSemanticEvaluationReceipt({
      oracleId: ORACLE_ID,
      outcome: 'PARTIAL_COVERAGE',
      expectationId: expectation.expectationId,
      sourceProvenance: expectation.sourceProvenance,
      invariantTotal: 1,
      invariantPassCount: 1,
      invariantNaCount: 0,
      invariantViolationCount: 0,
      findingCount: 0,
      coverageState: 'PARTIAL_COVERAGE_NO_VIOLATION',
      inspectedItemCount: 128,
      violatingItemCount: 0,
    });

    const leaks = sweepForSentinelLeaks(receipt);
    expect(leaks).toHaveLength(0);

    // Verify safe fields only — no raw IDs, no absolute paths.
    const serialized = JSON.stringify(receipt);
    expect(serialized).not.toContain('/home/');
    expect(serialized).not.toContain('/tmp/');
    expect(serialized).not.toContain('SENTINEL');
  });

  test('receipt built from anomaly evaluation has no sentinel leaks', () => {
    const body = Array.from({ length: 5 }, (_, i) => {
      if (i === 2) return { month: SENTINEL.WRONG_TYPE, exchange_rate: { usd: 1.0 } };
      return validExchangeItem(i);
    });
    const expectation = collectionExpectation();
    const result = evaluateCollection(body, expectation);
    expect(result.outcome).toBe('ANOMALY');

    const receipt = buildSemanticEvaluationReceipt({
      oracleId: ORACLE_ID,
      outcome: 'ANOMALY',
      expectationId: expectation.expectationId,
      sourceProvenance: expectation.sourceProvenance,
      projectionDigests: result.findings[0]?.projectionDigests ?? [],
      invariantTotal: 1,
      invariantPassCount: 0,
      invariantNaCount: 0,
      invariantViolationCount: 1,
      findingCount: 1,
      coverageState: 'VIOLATION',
      inspectedItemCount: 5,
      violatingItemCount: 1,
    });

    const leaks = sweepForSentinelLeaks(receipt);
    expect(leaks).toHaveLength(0);
  });

  test('sweep the full evaluation result for sentinel leaks', () => {
    const body = Array.from({ length: 130 }, (_, i) => {
      if (i === 0) return { month: SENTINEL.MONTH, exchange_rate: { usd: 1.0 } };
      if (i === 57) return { month: SENTINEL.WRONG_TYPE, exchange_rate: { usd: 57.0 } };
      if (i === 127) return { month: SENTINEL.NAME, exchange_rate: { usd: 127.0 } };
      return validExchangeItem(i);
    });
    const expectation = collectionExpectation();
    const result = evaluateCollection(body, expectation);

    // Sweep findings and invariant evaluations.
    expect(sweepForSentinelLeaks(result.findings)).toHaveLength(0);
    expect(sweepForSentinelLeaks(result.invariantEvaluations)).toHaveLength(0);
  });
});
