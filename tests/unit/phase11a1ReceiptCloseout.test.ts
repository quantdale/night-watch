/** Build a TYPE_MATCH collection-item contract for the `month` field. */
function monthTypeContract() {
  return createCollectionItemContract([], 'TYPE_MATCH', ['month'], {
    itemExpectedType: 'STRING',
  });
}

/** Create a collection-wide TYPE_MATCH expectation. */
function collectionExpectation(
  contracts = [monthTypeContract()],
): SemanticExpectation {
  return createCollectionExpectation(
    'ripple.common-exchange.read.real-source-collection',
    contracts,
  );
}

/** Run a collection-wide evaluation. */
function evaluateCollection(
  responseBody: unknown,
  expectation: SemanticExpectation,
  snapshotSha: string | null = FIXTURE_SHA,
) {
  return evaluateSemanticResponse({
    oracleId: ORACLE_ID,
    expectation,
    rawValues: [responseBody],
    sourceSnapshot: snapshotSha === null ? null : { repoId: PHASE11_PROVENANCE.repoId, sha: snapshotSha },
    journeyId: JOURNEY_ID,
    stepId: STEP_ID,
    operationId: expectation.targetId,
  });
}

/** Sweep a JSON-serializable value for raw sentinel leaks. */
function sweepForSentinelLeaks(value: unknown): string[] {
  const leaks: string[] = [];
  const text = JSON.stringify(value);
  const sentinels = [
    SENTINEL.MONTH, SENTINEL.RATE, SENTINEL.NAME,
    SENTINEL.ID, SENTINEL.NUMBER, String(SENTINEL.WRONG_TYPE),
  ];
  for (const s of sentinels) {
    if (text.includes(s)) leaks.push(s);
  }
  return leaks;
}

