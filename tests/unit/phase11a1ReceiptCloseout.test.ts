test.describe('Phase 11A.1 §1: receipt outcome mapping', () => {
  test('semanticOutcomeToReceiptOutcome maps PARTIAL_COVERAGE to PARTIAL_COVERAGE', () => {
    expect(semanticOutcomeToReceiptOutcome('PARTIAL_COVERAGE')).toBe('PARTIAL_COVERAGE');
  });

  test('PARTIAL_COVERAGE is in SEMANTIC_RECEIPT_NON_PASS_OUTCOMES', () => {
    expect(SEMANTIC_RECEIPT_NON_PASS_OUTCOMES.has('PARTIAL_COVERAGE')).toBe(true);
  });

  test('PASS is NOT in SEMANTIC_RECEIPT_NON_PASS_OUTCOMES', () => {
    expect(SEMANTIC_RECEIPT_NON_PASS_OUTCOMES.has('PASS')).toBe(false);
  });

  test('PARTIAL_COVERAGE is in the full SEMANTIC_RECEIPT_OUTCOMES list', () => {
    expect(SEMANTIC_RECEIPT_OUTCOMES).toContain('PARTIAL_COVERAGE');
  });

  test('every semantic non-pass outcome maps correctly through the hook', () => {
    // semanticOutcomeToReceiptOutcome takes SEMANTIC outcomes, not receipt
    // outcomes. Receipt-level concepts like NO_EXPECTATION are not semantic
    // outcomes and fall to INTERNAL_ERROR via the default case. Verify that
    // the core semantic outcomes (the ones generated by the runner) map to
    // their expected receipt counterparts.
    const semanticToReceipt: Array<[string, string]> = [
      ['PASS', 'PASS'],
      ['ANOMALY', 'ANOMALY'],
      ['NOT_APPLICABLE', 'NOT_APPLICABLE'],
      ['PARTIAL_COVERAGE', 'PARTIAL_COVERAGE'],
      ['EXPECTATION_UNAVAILABLE', 'EXPECTATION_SOURCE_UNAVAILABLE'],
      ['EXPECTATION_SOURCE_STALE', 'EXPECTATION_SOURCE_STALE'],
      ['INVALID_INPUT', 'INVALID_INPUT'],
      ['PROJECTION_LIMIT_EXCEEDED', 'PROJECTION_LIMIT_EXCEEDED'],
      ['EXPECTATION_INVALID', 'INTERNAL_ERROR'],
    ];
    for (const [semantic, receipt] of semanticToReceipt) {
      expect(semanticOutcomeToReceiptOutcome(semantic)).toBe(receipt);
    }
    // Unknown semantic outcomes fall to INTERNAL_ERROR.
    expect(semanticOutcomeToReceiptOutcome('UNKNOWN_XYZ')).toBe('INTERNAL_ERROR');
  });
});

