// 2. End-to-end receipt for 129 valid rows.
// ===========================================================================

test.describe('Phase 11A.1 §2: 129 valid rows produce PARTIAL_COVERAGE receipt', () => {
  test('129 valid exchange items evaluate to PARTIAL_COVERAGE and build receipt PARTIAL_COVERAGE', () => {
    const body = generateExchangeArray(129);
    const expectation = collectionExpectation();
    const result = evaluateCollection(body, expectation);

    // Semantic outcome must be PARTIAL_COVERAGE (129 > 128 projection cap).
    expect(result.outcome).toBe('PARTIAL_COVERAGE');
    const ev = result.invariantEvaluations.find(e => e.invariantKind === 'COLLECTION_ITEM_CONTRACT');
    expect(ev).toBeDefined();
    expect(ev!.verdict).toBe('PASS');
    expect(ev!.coverageState).toBe('PARTIAL_COVERAGE_NO_VIOLATION');
    expect(ev!.inspectedItemCount).toBe(128);
    expect(ev!.violatingItemCount).toBe(0);

    // Build receipt from the evaluation and verify it is PARTIAL_COVERAGE.
    const receipt = buildSemanticEvaluationReceipt({
      oracleId: ORACLE_ID,
      outcome: 'PARTIAL_COVERAGE',
      expectationId: expectation.expectationId,
      sourceProvenance: expectation.sourceProvenance,
      invariantTotal: 1,
      invariantPassCount: 1,
      invariantNaCount: 0,
      invariantViolationCount: 0,
      findingCount: 0,
      coverageState: 'PARTIAL_COVERAGE_NO_VIOLATION',
      inspectedItemCount: 128,
      violatingItemCount: 0,
      journeyId: JOURNEY_ID,
      stepId: STEP_ID,
      operationId: expectation.targetId,
    });

    expect(receipt.outcome).toBe('PARTIAL_COVERAGE');
    expect(receipt.coverageState).toBe('PARTIAL_COVERAGE_NO_VIOLATION');
    expect(receipt.inspectedItemCount).toBe(128);
    expect(receipt.violatingItemCount).toBe(0);
  });
});

